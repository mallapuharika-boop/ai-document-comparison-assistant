
from io import BytesIO

from docx import Document
from docx.shared import Inches, Pt


def generate_comparison_report(document_a, document_b, comparison):
    """Create a downloadable DOCX comparison report."""

    report = Document()

    # Page layout
    section = report.sections[0]
    section.top_margin = Inches(0.7)
    section.bottom_margin = Inches(0.7)

    # Default font
    normal_style = report.styles["Normal"]
    normal_style.font.name = "Arial"
    normal_style.font.size = Pt(10)

    # Report title
    report.add_heading("AI Document Comparison Report", level=0)
    report.add_paragraph(
        "Generated by the AI Document Comparison Assistant"
    )

    # Document A
    report.add_heading("1. Document A", level=1)
    report.add_paragraph(
        f"Filename: {document_a['filename']}"
    )
    report.add_paragraph(
        f"Pages: {document_a['page_count']}"
    )
    report.add_paragraph(
        comparison["document_a_summary"]
    )

    # Document B
    report.add_heading("2. Document B", level=1)
    report.add_paragraph(
        f"Filename: {document_b['filename']}"
    )
    report.add_paragraph(
        f"Pages: {document_b['page_count']}"
    )
    report.add_paragraph(
        comparison["document_b_summary"]
    )

    # Similarities
    report.add_heading("3. Similarities", level=1)

    if comparison["similarities"]:
        for item in comparison["similarities"]:
            report.add_paragraph(str(item), style="List Bullet")
    else:
        report.add_paragraph("No supported similarities were identified.")

    # Differences
    report.add_heading("4. Differences", level=1)

    if comparison["differences"]:
        for difference in comparison["differences"]:
            report.add_heading(
                str(difference.get("topic", "Difference")),
                level=2,
            )
            report.add_paragraph(
                f"Change type: {difference.get('change_type', 'Not specified')}"
            )
            report.add_paragraph(
                f"Document A: {difference.get('document_a', 'Not found')}"
            )
            report.add_paragraph(
                f"Document B: {difference.get('document_b', 'Not found')}"
            )
            report.add_paragraph(
                f"Evidence: {difference.get('evidence', 'Not provided')}"
            )
    else:
        report.add_paragraph("No supported differences were identified.")

    # Key details
    report.add_heading("5. Key Details Comparison", level=1)

    details = comparison["key_details"]

    if details:
        table = report.add_table(rows=1, cols=3)
        table.style = "Table Grid"

        headers = ["Detail", "Document A", "Document B"]

        for index, header in enumerate(headers):
            table.rows[0].cells[index].text = header

        for item in details:
            cells = table.add_row().cells
            cells[0].text = str(item.get("detail", "Not specified"))
            cells[1].text = str(
                item.get("document_a", "Not found in the provided text")
            )
            cells[2].text = str(
                item.get("document_b", "Not found in the provided text")
            )
    else:
        report.add_paragraph("No key details were returned.")

    # Conclusion
    report.add_heading("6. Overall Conclusion", level=1)
    report.add_paragraph(comparison["overall_conclusion"])

    # Limitations
    report.add_heading("7. Limitations", level=1)

    if comparison["limitations"]:
        for item in comparison["limitations"]:
            report.add_paragraph(str(item), style="List Bullet")
    else:
        report.add_paragraph(
            "No additional limitations were reported by the AI."
        )

    # Disclaimer
    report.add_paragraph(
        "Note: This report is an informational aid. "
        "AI-generated results may contain errors and should be verified "
        "against the original documents."
    )

    # Save the Word document in memory
    output = BytesIO()
    report.save(output)
    output.seek(0)

    return output.getvalue()
